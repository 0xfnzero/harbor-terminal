  await fs.writeFile(path.join(profile, 'preferences.json'), JSON.stringify({ language: 'zh-CN' }));
  const password = 'Harbor fixture passphrase 2026';
  const nextPassword = 'Harbor replacement phrase 2026';
  const options = { ...(process.env.HARBOR_EXECUTABLE ? { executablePath: process.env.HARBOR_EXECUTABLE } : {}), args: [...(process.env.HARBOR_EXECUTABLE ? [] : ['.']), `--user-data-dir=${profile}`], env: { ...process.env, HARBOR_DEV: '0' } };
