    await app.evaluate(({ powerMonitor }) => powerMonitor.emit('lock-screen'));
    await page.getByRole('heading', { name: '工作空间已锁定' }).waitFor();
    await app.close(); app = await electron.launch(options); page = await app.firstWindow(); page.setDefaultTimeout(15000);
    await page.getByRole('heading', { name: '工作空间已锁定' }).waitFor();
    await page.getByLabel('应用锁屏密码', { exact: true }).fill(nextPassword);
    await page.getByRole('button', { name: '解锁工作空间', exact: true }).click();
