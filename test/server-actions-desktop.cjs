const { _electron: electron } = require('playwright');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const net = require('node:net');
const assert = require('node:assert/strict');
(async () => {
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'harbor-server-actions-'));
  const listener = net.createServer(socket => socket.destroy());
  await new Promise(resolve => listener.listen(0, '127.0.0.1', resolve));
  let app;
  try {
    app = await electron.launch({ args: ['.', `--user-data-dir=${profile}`], env: { ...process.env, HARBOR_DEV: '0' } });
    const page = await app.firstWindow(); page.setDefaultTimeout(10000);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    await page.evaluate(async port => {
      for (const name of ['Development', 'Staging']) await window.harbor.saveServer({ name, host: '127.0.0.1', port, username: 'demo', persistent: false, autoReconnect: false });
    }, listener.address().port);
    await page.reload();
    const row = name => page.getByTitle(`Connect to ${name}`, { exact: true });
    const tabs = name => page.getByRole('tab', { name, exact: true });
    const menu = async name => { await row(name).hover(); await page.getByRole('button', { name: `More actions · ${name}`, exact: true }).click(); };
    await row('Development').click();
    await tabs('Development').waitFor();
    await row('Development').click();
    assert.equal(await tabs('Development').count(), 1);
    await menu('Development');
    await page.screenshot({ path: '/tmp/harbor-server-actions.png' });
    assert.equal(await page.getByRole('menuitem').count(), 3);
    assert.equal(await page.getByRole('menuitem').locator('svg').count(), 3);
    await page.getByRole('menuitem', { name: 'New', exact: true }).click();
    assert.equal(await tabs('Development').count(), 2);
    assert.equal(await tabs('Development').nth(1).getAttribute('aria-selected'), 'true');
    await tabs('Development').nth(0).click();
    await row('Development').click();
    assert.equal(await tabs('Development').nth(1).getAttribute('aria-selected'), 'true', 'select latest-created, not last-focused');
    await row('Staging').click();
    await tabs('Staging').waitFor();
    await row('Development').click();
    assert.equal(await tabs('Development').nth(1).getAttribute('aria-selected'), 'true');
    await page.getByRole('button', { name: 'Close Development', exact: true }).nth(1).click();
    await row('Development').click();
    assert.equal(await tabs('Development').count(), 1);
    assert.equal(await tabs('Development').getAttribute('aria-selected'), 'true');
    await page.getByRole('button', { name: 'Close Development', exact: true }).click();
    await row('Development').click();
    assert.equal(await tabs('Development').count(), 1, 'create if no matching tab even when another server has a tab');
    await menu('Development'); await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('menu').count(), 0);
    assert.equal(await page.getByRole('button', { name: 'More actions · Development' }).evaluate(e => e === document.activeElement), true);
    await menu('Development');
    await page.getByRole('menuitem', { name: 'Edit', exact: true }).click();
    await page.getByRole('textbox', { name: 'Connection name', exact: true }).fill('Development renamed');
    await page.getByRole('button', { name: 'Save connection', exact: true }).click();
    await row('Development renamed').waitFor();
    await row('Development renamed').click();
    assert.equal(await page.getByRole('tab').count(), 2, 'rename still matches existing tab by server ID');
    await menu('Development renamed'); await page.getByRole('menuitem', { name: 'Delete', exact: true }).click();
    await page.getByRole('dialog', { name: 'Delete server', exact: true }).waitFor();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.equal((await page.evaluate(() => window.harbor.listServers())).length, 2);
    await menu('Development renamed'); await page.getByRole('menuitem', { name: 'Delete', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm deletion', exact: true }).click();
    await row('Development renamed').waitFor({ state: 'detached' });
    assert.equal((await page.evaluate(() => window.harbor.listServers())).length, 1);
    assert.equal(await page.getByRole('tab').count(), 2, 'deleting configuration preserves open tabs');
    assert.deepEqual(errors, []);
    console.log('PASS server menu icons, new/edit/delete, keyboard dismissal and latest matching tab selection');
  } finally { if (app) await app.close(); await new Promise(resolve => listener.close(resolve)); await fs.rm(profile, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
