const { _electron: electron } = require('playwright');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const profile = await fs.mkdtemp(path.join(os.tmpdir(), 'harbor-language-ui-'));
  const options = { ...(process.env.HARBOR_EXECUTABLE ? { executablePath: process.env.HARBOR_EXECUTABLE } : {}), args: [...(process.env.HARBOR_EXECUTABLE ? [] : ['.']), `--user-data-dir=${profile}`], env: { ...process.env, HARBOR_DEV: '0' } };
  let app;
  try {
    app = await electron.launch(options);
    let page = await app.firstWindow(); page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    async function select(label, value) {
      await page.getByRole('combobox', { name: label, exact: true }).click();
      await page.locator(`[role=option][data-value="${value}"]`).click();
    }
    await page.getByRole('heading', { name: 'Pick up where you left off.' }).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    await page.getByRole('button', { name: 'Add your first server' }).click();
    await page.getByLabel('Connection name', { exact: true }).fill('生产服务器');
    await page.getByLabel('Host address / SSH alias', { exact: true }).fill('test.example.com');
    await page.getByRole('tab', { name: 'Authentication', exact: true }).click();
    await select('Authentication method', 'key');
    await page.getByRole('button', { name: 'Save connection', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Select a private key or PEM file' }).waitFor();
    await page.getByLabel('Private key / PEM file', { exact: true }).fill('/tmp/语言-test.pem');
    await page.getByRole('tab', { name: 'Network & session', exact: true }).click();
    await page.getByRole('checkbox', { name: /^Automatically reconnect/ }).waitFor();
    await page.screenshot({ path: path.join(os.tmpdir(), 'harbor-language-server-en.png') });
    await page.getByRole('button', { name: 'Save connection', exact: true }).click();
    await page.getByTitle('Connect to 生产服务器', { exact: true }).waitFor();
    const saved = await fs.readFile(path.join(profile, 'servers.json'), 'utf8');
    const backendError = await page.evaluate(async () => { try { await window.harbor.saveServer({ host: 'localhost' }); } catch(e) { return e.message; } });
    assert.match(backendError, /Enter a server name/);
    await page.getByRole('button', { name: 'Open local terminal', exact: true }).click();
    await page.getByText('Local session', { exact: true }).waitFor();
    await page.evaluate(() => { window.languageOutput = ''; window.harbor.onEvent(e => { if (e.type === 'data') window.languageOutput += e.data; }); });
    await page.locator('.terminal-pane.active .xterm-helper-textarea').focus();
    await page.keyboard.insertText(process.platform === 'win32' ? '$harborLanguage="retained"; Write-Output ("LANG_PID=" + $PID)' : 'HARBOR_LANGUAGE=retained; printf "LANG_PID=%s\\n" "$$"'); await page.keyboard.press('Enter');
    await page.waitForFunction(() => /LANG_PID=\d+/.test(window.languageOutput));
    const pid = await page.evaluate(() => window.languageOutput.match(/LANG_PID=(\d+)/)[1]);
    const sessions = await page.evaluate(() => window.harbor.listSessions());
    await select('Language / 语言', 'zh-CN');
    await page.getByRole('tab', { name: '本地终端', exact: true }).waitFor();
    await page.getByText('本地会话', { exact: true }).waitFor();
    await page.getByTitle('连接 生产服务器', { exact: true }).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN');
    const nativeMenu = await app.evaluate(({ Menu }) => Menu.getApplicationMenu().items.map(i => i.label));
    assert.ok(nativeMenu.includes('编辑'));
    await select('Language / 语言', 'en');
    await page.getByRole('tab', { name: 'Local terminal', exact: true }).waitFor();
    await page.locator('.terminal-pane.active .xterm-helper-textarea').focus();
    await page.keyboard.insertText(process.platform === 'win32' ? 'Write-Output ("LANG_AFTER=" + $PID + ":" + $harborLanguage)' : 'printf "LANG_AFTER=%s:%s\\n" "$$" "$HARBOR_LANGUAGE"'); await page.keyboard.press('Enter');
    await page.waitForFunction(() => /LANG_AFTER=\d+:retained/.test(window.languageOutput));
    assert.equal(await page.evaluate(() => window.languageOutput.match(/LANG_AFTER=(\d+):retained/)[1]), pid);
    assert.deepEqual(await page.evaluate(() => window.harbor.listSessions()), sessions);
    assert.equal(await fs.readFile(path.join(profile, 'servers.json'), 'utf8'), saved, 'language changes never rewrite server settings');
    await page.getByRole('button', { name: 'Appearance', exact: true }).click();
    await page.getByRole('dialog', { name: 'Appearance', exact: true }).waitFor();
    await page.getByText('Deep-sea mint', { exact: false }).waitFor();
    await page.locator('summary').filter({ hasText: 'Custom colors' }).click();
    await page.getByLabel('Background color picker').waitFor();
    await page.screenshot({ path: path.join(os.tmpdir(), 'harbor-language-appearance-en.png') });
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByRole('button', { name: 'Components', exact: true }).click();
    await page.getByRole('dialog', { name: 'Optional components · Mosh' }).waitFor();
    await page.getByRole('checkbox', { name: 'I understand the location and changes, and allow installation' }).waitFor();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    await page.getByRole('button', { name: 'Security', exact: true }).click();
    await page.getByLabel('Set app lock password', { exact: true }).fill('language-test-passphrase');
    await page.getByLabel('Confirm app lock password', { exact: true }).fill('language-test-passphrase');
    await page.getByRole('button', { name: 'Enable encryption', exact: true }).click();
    await page.getByRole('dialog', { name: 'Security & lock screen' }).waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Lock', exact: true }).click();
    await page.getByRole('heading', { name: 'Workspace locked' }).waitFor();
    await select('Language / 语言', 'zh-CN');
    await page.getByRole('heading', { name: '工作空间已锁定' }).waitFor();
    assert.equal((await page.evaluate(() => window.harbor.getSecurity())).locked, true);
    await app.close(); app = await electron.launch(options); page = await app.firstWindow(); page.setDefaultTimeout(15000);
    await page.getByRole('heading', { name: '工作空间已锁定' }).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'), 'zh-CN');
    await select('Language / 语言', 'en');
    await page.getByLabel('App lock password', { exact: true }).fill('language-test-passphrase');
    await page.getByRole('button', { name: 'Unlock workspace', exact: true }).click();
    await page.getByTitle('Connect to 生产服务器', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(os.tmpdir(), 'harbor-language-welcome-en.png') });
    await app.close(); app = await electron.launch(options); page = await app.firstWindow();
    await page.getByRole('heading', { name: 'Workspace locked' }).waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    assert.deepEqual(errors, []);
    console.log('PASS English default, bilingual forms/menu, unmodified server values, unchanged shell PID, locked-language switching and preference persistence in both languages');
  } catch(e) {
    if (app) { const page = await app.firstWindow(); await page.screenshot({ path: path.join(os.tmpdir(), 'harbor-language-failure.png') }).catch(() => {}); console.error(await page.locator('body').innerText().catch(() => '')); }
    throw e;
  } finally { if (app) await app.close(); await fs.rm(profile, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
